// Generates src/styles/type.css: every body / supporting-text font size in the
// site's stylesheets, increased by 2px. Headings, display type, labels, buttons,
// navigation and tiny UI chrome are left alone.
//
// Run:  node scripts/build-type.mjs   (re-run after adding new text styles)

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const BUMP = '2px';
const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'styles');
const FILES = ['global.css', 'components.css', 'sections.css', 'pages.css', 'theme.css', 'brand.css', 'talk.css', 'polish.css'];

// Not "subtext": headings, labels, controls, decorative type.
const SKIP =
  /(\bh[1-4]\b|\.pv\b|index|who-badge|who-fact strong|tform-submit|askbot-chip|display|title|metric|stat-n|nav|mega|btn|logo|bm-|tool-|orbit|chip|eyebrow|label|badge|tag|kind|-num|-n\b|uc2-cat|uc2-n|intro|marquee|svc-pill|sector-pill|wordmark|ufield|reach-txt b|reach-email|reach-head|reach-areas|reach-check|tform-badge|cursor|curtain|skip|work-tab|uc-filter|sc-btn|sc-gauge|plan-chip|hero-ticker|askbot-fab|askbot-title|acc-text|acc-num|voice-a|voice-b|voices-end|mirror|gcard|pv-|integ-core|footer-col h4|cta-line span|cta-next-k|feature-case-head|work-headline|work-client|work-modal-headline|why2-caption|about-quote|persona-k|pack-tagline|pack-name|svc-phil|mf-|manifesto|core-title|method-title|funnel-title|uc-title|journey-stage|journey-k|footer-closer|hero2-caption|tl-k|cat-title|sector-card h3|pack-for-text|next-pack|page-hero|hero-scroll|hero-proof-sep|scroll)/;

const toPx = (v) => {
  const vals = [...v.matchAll(/([\d.]+)(rem|px|em)/g)].map(([, n, u]) => (u === 'px' ? +n : +n * 16));
  return vals.length ? Math.max(...vals) : null;
};

const out = postcss.root();
const seen = new Set();

for (const file of FILES) {
  const ast = postcss.parse(readFileSync(join(root, file), 'utf8'), { from: file });
  ast.walkDecls('font-size', (decl) => {
    const rule = decl.parent;
    if (rule.type !== 'rule') return;
    if (/\bvar\(|calc\(/.test(decl.value)) return;
    const px = toPx(decl.value);
    if (px == null || px < 12 || px > 21) return; // subtext range only
    const selectors = rule.selectors.filter((s) => !SKIP.test(s));
    if (!selectors.length) return;

    // Rebuild the at-rule chain (e.g. @media) around the override.
    let target = out;
    const chain = [];
    for (let p = rule.parent; p && p.type === 'atrule'; p = p.parent) chain.unshift(p);
    for (const at of chain) {
      const key = `@${at.name} ${at.params}`;
      let found = target.nodes.find((n) => n.type === 'atrule' && `@${n.name} ${n.params}` === key);
      if (!found) {
        found = postcss.atRule({ name: at.name, params: at.params });
        target.append(found);
      }
      target = found;
    }
    const sig = `${chain.map((c) => c.params).join('|')}::${selectors.join(',')}::${decl.value}`;
    if (seen.has(sig)) return;
    seen.add(sig);
    target.append(
      postcss.rule({ selectors }).append(postcss.decl({ prop: 'font-size', value: `calc(${decl.value} + ${BUMP})` }))
    );
  });
}

const header = '/* Generated by scripts/build-type.mjs — supporting text +2px. Do not edit by hand. */\n';
writeFileSync(join(root, 'type.css'), header + out.toString() + '\n');
let count = 0;
out.walkRules(() => count++);
console.log(`✓ type.css — ${count} text styles increased by ${BUMP}`);
