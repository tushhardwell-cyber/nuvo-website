export function brandFor(name) {
  const k = name.toLowerCase().trim();
  const key = ALIASES[k] || k.replace(/[^a-z0-9]/g, '');
  return BRANDS[key] || { label: name, mark: name.slice(0, 2), color: '#5a6178' };
}
